cadena = ' Python es divertido ' # Definimos una cadena con espacios al inicio y al final
# Quita espacios en los bordes
cadena_limpia = cadena.strip() # Eliminamos los espacios en blanco al inicio y al final de la cadena
# Cuenta la longitud
cantidad = len(cadena_limpia) # Calculamos la cantidad de caracteres de la cadena limpia


print(f"Cadena limpia: '{cadena_limpia}'") # Mostramos la cadena sin espacios en los extremos
print(f"Caracteres: {cantidad}") # Mostramos la cantidad total de caracteres